// CPU checks for the cascade fit. The picture gates live in csm-gate.mjs.
import { FOV_Y } from '../engine/bricks/follow-cam.js';
import { shadeAt, shadeAtSh, lightWgsl, gradeLinear } from '../biome-factory/light-rig.js';
import { ICE, litIce } from './albedo.js';
import { LIGHT, DRAWS, LIMITS } from './biome.js';
import { buildWorld } from './world.js';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { SHADOW_DRAWS, buildCascades, applyMat, practicalSplit, snapCenter, lightAxes } from './shadows.js';

const limits = JSON.parse(fs.readFileSync(path.join(path.dirname(fileURLToPath(import.meta.url)), 'csm-limits.json'), 'utf8'));
let fail = 0;
const bad = (m) => { console.error('FAIL', m); fail++; };
if (limits.csmIouMin !== 0.8 || limits.edgeShimmerMax !== 0.005 || limits.cascadeSeamJumpMax !== 0.03) bad('threshold moved');
if (limits.snowShadowBlueMin !== 0.03 || limits.crossCameraDe76Max !== 10 || limits.clipFracMax !== 0.005) bad('colour threshold moved');
if (DRAWS.length !== 9 || SHADOW_DRAWS.length !== 5 || SHADOW_DRAWS.length > LIMITS.draws) bad('draw budget');
const world = buildWorld();
if (world.budget.totalTris !== 195634) bad('tris ' + world.budget.totalTris);
if (world.budget.draws !== 9) bad('draws');
const split = practicalSplit(1, 2, 1, 120, 0.7);
if (Math.abs(split - 25) > 1.2) bad('split ' + split);
const aspect = 720 / 1280;
const sun = LIGHT.sun.direction;
const eye = [2, 3, 10];
const tgt = [2, 2.2, -20];
const a = buildCascades({ eye, tgt, fovY: FOV_Y, aspect, sun, tier: 'phone' });
if (a.splits[1] !== 25 || a.atlas[0] !== 2048 || a.atlas[1] !== 1024) bad('phone fit');
const texel = (2 * a.radii[0]) / a.tile;
const { s } = lightAxes(sun);
const on = snapCenter([0, 2, 0], sun, a.radii[0], a.tile);
const held = snapCenter(on.map((v, i) => v + s[i] * texel * 0.2), sun, a.radii[0], a.tile);
if (held.some((v, i) => Math.abs(v - on[i]) > 1e-3)) bad('snap drifted inside a texel');
const q = applyMat(a.mats[0], a.centers[0]);
if (Math.abs(q[0]) > 0.03 || Math.abs(q[1]) > 0.03 || q[2] < 0.2 || q[2] > 0.8) bad('centre ' + q);
const lit = shadeAt(LIGHT, 1, 1);
const same = shadeAtSh(LIGHT, 1, 1, 1);
const dark = shadeAtSh(LIGHT, 1, 1, 0);
if (lit.rgb.some((v, i) => Math.abs(v - same.rgb[i]) > 1e-6)) bad('dawnIrrSh drifted');
if (dark.rgb.some((v, i) => Math.abs(v - LIGHT.ambient.rgb[i]) > 1e-6)) bad('shadow ate ambient');
if (ICE.sheen > 0.21) bad('F0');
const wgsl = lightWgsl(LIGHT);
const dawn = wgsl.slice(wgsl.indexOf('fn dawnIrr('), wgsl.indexOf('fn dawnIrrSh'));
if (dawn.includes('sh')) bad('dawnIrr mentions sh');
const full = litIce(ICE.snow, [0, 1, 0], [0, 0.3, 1], LIGHT, 1);
const dim = litIce(ICE.snow, [0, 1, 0], [0, 0.3, 1], LIGHT, 0);
const br = (c) => c[2] - c[0];
const dLit = gradeLinear(full, LIGHT);
const dDim = gradeLinear(dim, LIGHT);
if (!(br(dDim) > br(dLit) + 0.03)) bad('display shadow not bluer');
const high = buildCascades({ eye, tgt, fovY: FOV_Y, aspect, sun, tier: 'high' });
if (high.count !== 4 || high.atlas[0] !== 2048) bad('high tier');
if (fail) process.exit(1);
console.log('PASS csm-cpu', JSON.stringify({ radii: a.radii.map((v) => +v.toFixed(2)), split: +split.toFixed(2), tris: world.budget.totalTris }));
