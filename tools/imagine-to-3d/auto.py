def sh(*a, env=None, check=False, timeout=None):
    print("+", " ".join(map(str, a)), flush=True)
    r = subprocess.run([str(x) for x in a], env=dict(os.environ, **(env or {})), capture_output=True, text=True, timeout=timeout)
    if check and r.returncode: raise RuntimeError(f"{a[1] if len(a) > 1 else a[0]} exit {r.returncode}: {r.stderr[-800:]}")
    return r


