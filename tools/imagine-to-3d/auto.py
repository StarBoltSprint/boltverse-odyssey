    def s_inputs(self):
        sp = self.spec; im = sp.get("imagine", {}); bad, info = [], []
        files = []
        for k, v in (im.get("views") or {}).items(): files.append(("view", k, v))
        if im.get("plates"):
            pj = json.load(open(im["plates"]))
            walls = set(pj.get("walls", []))
            for w, p in pj.get("imagine", {}).items(): files.append(("plate" if (w in walls or not walls) else "plate-unused", w, p))
        for p in sorted(glob.glob(os.path.join(im.get("detailSrc", "/nonexistent"), "*.png"))): files.append(("detail", os.path.basename(p), p))
        for p in im.get("sectionTex", []): files.append(("section", os.path.basename(p), os.path.join(im.get("sectionTexDir", ""), p)))
        ex = set(str(x) for x in (im.get("excludePlates") or []))
        if im.get("plateDir"):
            globs_ = im.get("plateGlob") or ["*.jpg", "*.png"]
            if isinstance(globs_, str): globs_ = [globs_]
            for gpat in globs_:
                for p in sorted(glob.glob(os.path.join(im["plateDir"], gpat))):
                    name = os.path.splitext(os.path.basename(p))[0]
                    if name in ex: continue
                    files.append(("plate", name, p))
        raw = sorted(glob.glob(os.path.join((sp.get("grade") or {}).get("rawDir") or "/nonexistent", "raw*.rgba")))
        for p in raw:   # decoded Imagine section cells: must be exactly 1024² (never resized)
            if os.path.getsize(p) != 1024 * 1024 * 4: bad.append(dict(kind="section-raw", id=os.path.basename(p), why="not a 1024² RGBA cell"))
            info.append(dict(kind="section-raw", id=os.path.basename(p), size=[1024, 1024], native=True))
        from PIL import Image
        natives = set(C.IMAGINE_NATIVE.values()) | {(1376, 752), (752, 1376)}
        for kind, k, p in files:
            if not os.path.exists(p): bad.append(dict(kind=kind, id=k, path=p, why="missing")); continue
            w, h = Image.open(p).size
            native = (w, h) in natives
            crop = not native and w <= 1376 and h <= 1376          # recorded crops of a native image (e.g. 928² seamless interior)
            if not native and not crop: bad.append(dict(kind=kind, id=k, path=p, size=[w, h], why="larger than any Imagine native size (upscaled?)"))
            info.append(dict(kind=kind, id=k, size=[w, h], native=native))
        groups = self.plate_groups(files)
        distinct = len(set(groups.values())) if groups else 0
        need = int(sp.get("geometry", {}).get("minDistinctWallPlates", 0))
        req = None
        if need and distinct < need:
            req = self.imagine_requests(need - distinct, files)
        st = "FAIL" if bad else ("NEEDS_IMAGINE" if req else "PASS")
        return self.done("inputs", st, files=len(files) + len(raw), bad=bad, plateGroups=groups, distinctWallPlates=distinct, minDistinct=need,
                         imagineBatch=req, summary=f"{len(files) + len(raw)} Imagine files, {len(bad)} bad, {distinct} distinct wall plates (need {need})")

    def plate_groups(self, files):
        from PIL import Image
        ex = set(self.spec.get("imagine", {}).get("excludePlates", []))
        ps = [(k, p) for kind, k, p in files if kind == "plate" and os.path.exists(p) and k.startswith("w") and k not in ex]
        A = {k: np.asarray(Image.open(p).convert("L").resize((320, 180)), float).ravel() for k, p in ps}
        g = {}
        for i, (k, _) in enumerate(ps):
            g[k] = k
            for k2, _ in ps[:i]:
                if np.corrcoef(A[k], A[k2])[0, 1] > 0.9: g[k] = g[k2]; break
        return g

    def imagine_requests(self, n, files):
        """write (never run) an Imagine request batch for n new distinct wall plates, refs = key crop + one existing plate."""
        from imagine import Request, write_batch
        crop = self.spec["crop"]; plates = [p for kind, k, p in files if kind == "plate" and k.startswith("w")]
        reqs = [Request(id=f"wall-new-{i + 1}", kind="edit", aspect="16:9", refs=[crop, plates[i % len(plates)]],
                        prompt=("<IMAGE_1> rock: a NEW straight-on 16 m wide section of the same sandstone cliff wall, same light and colours as "
                                "<IMAGE_2> but a clearly different bedding / fracture / erosion pattern (no brick grid, no repeated blocks), fills the frame, "
                                "no sky, no ground, no text."), out=os.path.join(self.work, "imagine-req", f"wall-new-{i + 1}.jpg"),
                        purpose="distinct wall plate for the no-repetition rule")
                for i in range(n)]
        os.makedirs(os.path.join(self.work, "imagine-req"), exist_ok=True)
        return write_batch(reqs, os.path.join(self.work, "imagine-req", "batch-walls.json"), note="auto.py NEEDS_IMAGINE (not run; needs approval)")

    def s_consistency(self):
        """Locked palette + image consistency (mandatory). spec.palette: {file, materials: {view|plate|detail|section: material},
        keyRect: {material: [x0,y0,x1,y1]}, strength, useGraded}. Grades into WORK/graded (originals untouched)."""
        import palette as PAL, consistency as CO
        pc = self.spec.get("palette")
        if not pc: return self.done("consistency", "FAIL", reason="no `palette:` in the spec: the locked palette + consistency check is mandatory (palette.py sample once per biome)")
        P = json.load(open(pc["file"])); key = self.spec.get("key") or P["key"]; out = os.path.join(self.work, "consistency"); os.makedirs(out, exist_ok=True)
        rp = os.path.join(out, "imagine-requests.json")
        if os.path.exists(rp): os.remove(rp)
        im = self.spec.get("imagine", {}); excl = set(im.get("excludePlates") or [])
        files = [dict(kind="view", id=k, path=v) for k, v in (im.get("views") or {}).items()]
        if im.get("plates"):
            pj = json.load(open(im["plates"])); walls = set(pj.get("walls", []))
            files += [dict(kind="plate", id=w, path=p) for w, p in pj.get("imagine", {}).items() if w not in excl and (w in walls or not walls)]
        mats = pc.get("materials", {}); graded, log, verdicts = {}, os.path.join(out, "palette-log.jsonl"), []
        by_mat = {}
        for f in files:
            kind, fid, path = f["kind"], f["id"], f["path"]
            mat = mats.get(fid) or mats.get(kind)
            if not mat or kind.endswith("unused") or not os.path.exists(path): continue
            dst = os.path.join(out, "graded", f"{kind}-{os.path.basename(path)}")
            PAL.grade(path, P, mat, dst, pc.get("strength", 0.8), log); graded[path] = dst; by_mat.setdefault((mat, kind), []).append(dst)
        for (mat, kind), imgs in by_mat.items():
            r = CO.check(imgs, key, P, mat, (pc.get("keyRect") or {}).get(mat), out, self.type if self.type != "auto" else None); verdicts.append(r["verdict"])
        views = [graded.get(v, v) for v in (self.spec.get("imagine", {}).get("views") or {}).values()]
        if len(views) >= 2: verdicts.append(CO.views(views, None, out)["verdict"])
        if pc.get("useGraded"):   # downstream stages read the graded copies (in memory only; the spec file is not edited)
            for k, v in list((self.spec.get("imagine", {}).get("views") or {}).items()): self.spec["imagine"]["views"][k] = graded.get(v, v)
        reqs = json.load(open(rp)) if os.path.exists(rp) else []
        st = "FAIL" if "FAIL" in verdicts else ("NEEDS_IMAGINE" if "FLAG" in verdicts else "PASS")
        return self.done("consistency", st, dir=out, graded=len(graded), imagineRequests=rp if reqs else None,
                         summary=f"{len(graded)} images graded (log {log}); checks {verdicts}; {len(reqs)} Imagine requests (not run)")

    def s_keycompare(self):
        """Key image vs key camera for this object's key elements (mandatory); below target -> fixloop keyloop."""
        kc = self.spec.get("keyCompare")
        if not kc: return self.done("keycompare", "FAIL", reason="no `keyCompare:` in the spec: the key-image comparison is mandatory")
        import fixloop
        base = os.path.dirname(self.spec_path); spec_abs = kc["spec"] if os.path.isabs(kc["spec"]) else os.path.join(base, kc["spec"])
        out = os.path.join(self.work, "keycompare")
        cmd = ["node", os.path.join(C.OBJECT_GATE_DIR, "key-compare.mjs"), "--spec", spec_abs, "--out", out, "--only", ",".join(kc["elements"])]
        if self.spec.get("stagingUrl") or kc.get("url"): cmd += ["--url", self.spec.get("stagingUrl") or kc.get("url")]
        if kc.get("camera"): cmd += ["--camera", kc["camera"]]
        r = sh(*cmd, timeout=7200); st = {0: "PASS", 1: "FAIL"}.get(r.returncode, "ERROR")
        loop = None
        F = fixloop.collect_key_compare(os.path.join(out, "key-compare.json"), include_gaps=True) if os.path.exists(os.path.join(out, "key-compare.json")) else []
        if F and kc.get("autoFix", True):
            loop = fixloop.keyloop(self.spec_path)
            last = loop["history"][-1]["verdict"]; st = "PASS" if last == "PASS" else "FAIL"
        return self.done("keycompare", st, dir=out, sheet=os.path.join(out, "sheet.jpg"), loop=loop and dict(status=loop["status"], rounds=loop["rounds"], notWired=loop["notWired"], requests=len(loop["imagineRequests"])),
                         summary=f"key-compare exit {r.returncode}" + (f"; keyloop {loop['status']} after {loop['rounds']} rounds" if loop else ""))

