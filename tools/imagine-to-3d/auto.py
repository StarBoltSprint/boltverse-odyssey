"""imagine-to-3d AUTO: one command from existing Imagine images to a gated, phone-budgeted, staged object.
Every lesson of 2026-10-08..10 is a stage with a hard check; nothing ships on a FAIL and no stage ever generates an
Imagine image (missing / insufficient Imagine input -> NEEDS_IMAGINE + a request batch for imagine.py, not run).

  python3 auto.py run   spec.yaml [--stages a,b,...] [--from stage]     # run (skips stages whose outputs are fresh)
  python3 auto.py plan  spec.yaml                                         # print the stage plan + what is manual
  python3 auto.py report WORK                                             # REPORT.md from state.json

Stages (order; each writes WORK/<stage>.json and updates WORK/state.json):
  inputs    Imagine inputs exist, native size (no upscale, no stretch > 1.25), provenance; near-duplicate plates grouped
  classify  type from the key crop (classify.py) unless spec.type is set
  shape     hull -> fused DA-V2 depth (cross-view consistency) -> per-plate depth relief (run.py strata stages)
  geometry  CONTINUOUS strata/surfaces (strata2.py: one wall per section, joint-blended plate windows, smooth welded
            normals, rotated/toned fallen blocks) + shape-seed search to outline IoU >= iouMin and window salts until
            no repetition (gen_strata_all.py, GEN=strata2.py). Same shell at every LOD, relief as an attribute.
  pack      int16 + index + gzip, LOD2 dropped, LOD0 on demand, gen-summary.json copied (pack_strata.py)
  detail    tiling Imagine detail layer (~512 px/m, hex 3-tap, DA-V2 normals) from EXISTING seamless Imagine crops
            (detail/bake_detail.py) + texture-space no-repetition check (detail/repeat_check.py) -> detail.json
  grade     offline grading of section plates with the runtime's own functions -> R8 brightness atlases + low-res chroma
  stage     copy packed geometry / atlases / detail into the STAGING dir (refuses the live tree)
  shaders   dump the staging page's fragment shaders (checks/dump-shaders.mjs)      [browser]
  perf      per-object budget at the full pixel ratio (checks/perf_budget.py)
  morph     approach-morph 300 -> 10 -> 300 m, camera outside the collision hull (checks/approach-morph.mjs) [browser]
  gate      object-gate CLI (PR #191 thresholds) on the staging page, zero FAIL; FAIL -> fixloop.py plan      [browser]
  report    REPORT.md: every row, what passed, what needs Imagine, what is still manual
"""
